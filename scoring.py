"""
Turning two numbers into one, and one number into something a person can read.

`combine_signals` is where your false-positive decision from Milestone 1
actually gets made. Everything above it — the labels, the appeal path — is
downstream of a number this function produced.

`score_to_label` is where you stop writing for a machine and start writing for
a person. A score of 0.62 means nothing to a writer.

⚠️ Your README's **Signals and Scoring** section has to name the file and
function holding your combining rule. The grader checks your code against what
you claim, so that line should read `scoring.py::combine_signals`.
"""

import math

import config


def combine_signals(model_score: float, style_score: float) -> float:
    """
    Combine finite 0–1 signals with the configured nonnegative weights.

    Both inputs point the same way: higher means more likely AI. Your output
    should too.

    Args:
        model_score: from `detector.model_signal` — how predictable the text is.
        style_score: from `stylometry.style_signal` — the shape of the text.

    Returns:
        A float from 0.0 (confidently human) to 1.0 (confidently AI).

    ⚠️ **Write the rule down before you code it, and put the numbers in your
    README.** A weighted average is the obvious choice and it is not the only
    one. Things worth thinking about:

      - **What happens when they disagree?** One signal at 0.9 and the other at
        0.1 averages to 0.5 — "unsure". Is that what you want? It might be
        exactly right: two methods disagreeing IS uncertainty. Or you might
        decide one signal is more trustworthy when they split.

      - **Which way do you want to be wrong?** Weighting toward the signal that
        reads more human means fewer false accusations and more AI text
        getting through. There's no weighting that avoids the trade.

      - Milestone 4 asks you to find a case where your two signals split and
        write it down. That case is what this rule exists to handle.

    The baseline and current weights are documented in README.md.
    """
    if any(not math.isfinite(score) or not 0.0 <= score <= 1.0 for score in (model_score, style_score)):
        raise ValueError("Signal scores must be finite numbers from 0 to 1.")
    model_weight, style_weight = config.WEIGHT_MODEL_SIGNAL, config.WEIGHT_STYLE_SIGNAL
    if any(not math.isfinite(weight) or weight < 0.0 for weight in (model_weight, style_weight)):
        raise ValueError("Signal weights must be finite and nonnegative.")
    total = model_weight + style_weight
    if total <= 0.0 or not math.isfinite(total):
        raise ValueError("Signal weights must have a finite, positive total.")
    score = (model_weight * model_score + style_weight * style_score) / total
    return round(min(max(score, 0.0), 1.0), 4)


def score_to_label(score: float) -> tuple[str, str]:
    """Return the machine-readable guess and the label shown to the writer."""
    if score >= config.AI_THRESHOLD:
        return "ai", "This looks AI-generated. If you wrote it, you can request a review."
    if score <= config.HUMAN_THRESHOLD:
        return "human", "We think this was probably written by a person. You don't need to do anything."
    return "unsure", (
        "We couldn't tell whether this was written by a person or generated by AI. "
        "If you'd like us to take a closer look, you can request a review."
    )


def label_ranges() -> list[tuple[str, str]]:
    """
    The score range each label covers. Your README needs these beside the
    label text — given to you so the numbers can't drift apart from config.py.
    """
    return [
        ("high-confidence human", f"0.00 ≤ score ≤ {config.HUMAN_THRESHOLD:g}"),
        ("unsure", f"{config.HUMAN_THRESHOLD:g} < score < {config.AI_THRESHOLD:g}"),
        ("high-confidence AI", f"{config.AI_THRESHOLD:g} ≤ score ≤ 1.00"),
    ]
